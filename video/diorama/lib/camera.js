const tr = track(KEYS);

export function placeCamera(cam, t) {
  const [x, y, z, ld, yaw, pitch] = tr(t), d = Math.exp(ld);
  cam.position.set(x + d * Math.sin(yaw) * Math.cos(pitch), y + d * Math.sin(pitch), z + d * Math.cos(yaw) * Math.cos(pitch));
  cam.lookAt(x, y, z);
  cam.near = d * 0.05; cam.far = d * 12; cam.updateProjectionMatrix();
  return { x, y, z, d };
}
